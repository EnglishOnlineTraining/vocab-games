#!/usr/bin/env node
'use strict';

/*
 * build-wordpress-hub.js — the desired state of the button labels on
 * WordPress page 1763 (englishonline.training/activities/), derived from
 * data/exercises.json.
 *
 * WHY THIS IS A DATA FILE AND NOT AN API CALL
 * The build graph cannot write to WordPress: GitHub Actions holds no WordPress
 * credentials, and the WordPress MCP is a tool driven from a Claude session, not
 * something CI can run. So the repo owns the *answer* — what each button should
 * say — and applying it stays a session step (see "Update WordPress page 1763"
 * in the exercise-creating skills).
 *
 * That split is what makes the manual step safe: it is no longer "remember to
 * bump some numbers", it is "make the live page match this file". The counts
 * drift badly when nobody computes them — on 2026-09-09 six of the fourteen were
 * wrong and Year 10 Gymnasium read 20 against a real 27.
 *
 * The count for a category is its entry count in data/exercises.json, which is
 * the same figure the per-category hub and the root page show.
 */

const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const BASE = 'https://activities.englishonline.training/';

const exercises = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', 'exercises.json'), 'utf8'));
const n = (year, school) => exercises.filter(e =>
  String(e.year) === String(year) && (!school || e.schoolType === school)).length;

// One row per counted button on 1763, in page order. `hub` is the key the
// button is matched on — an href is stable, the label is what changes.
const BUTTONS = [
  ['Year 7',          '7g-activities.html',       '🏫 Gymnasium',        n(7, 'gymnasium')],
  ['Year 7',          '7c-activities.html',       '🏫 Oberschule',       n(7, 'oberschule')],
  ['Year 8',          '8g-activities.html',       '🏫 Gymnasium',        n(8, 'gymnasium')],
  ['Year 8',          '8c-activities.html',       '🏫 Oberschule',       n(8, 'oberschule')],
  ['Year 9',          '9g-activities.html',       '🏫 Gymnasium',        n(9, 'gymnasium')],
  ['Year 9',          '9c-activities.html',       '🏫 Oberschule',       n(9, 'oberschule')],
  ['Year 10',         '10g-activities.html',      '🏫 Gymnasium',        n(10, 'gymnasium')],
  ['Year 10',         '10c-activities.html',      '🏫 Oberschule',       n(10, 'oberschule')],
  ['Abitur (Sek II)', 'abitur-activities.html',   '🎓 Abitur English',   n('abitur')],
  ['MSA',             'msa-activities.html',      '🎧 MSA English',      n('msa')],
  ['University',      'uni-activities.html',      '🎓 University',       n('uni')],
  ['IT English',      'it-activities.html',       '💻 IT English',       n('it')],
  ['Business English','business-activities.html', '💼 Business English', n('business')],
  // Not generated in sync with anything on the page above it, which is exactly
  // why it went stale once already: it read "(2 exercises)" while 15 gr-* pages
  // were live.
  ['Nach Grammatik-Thema üben', 'grammar-activities.html', '✏️ Grammatik-Übungen', n('grammar')]
];

const out = {
  _readme: 'Desired button labels for WordPress page 1763. Generated by '
    + 'scripts/build-wordpress-hub.js — do not hand-edit. CI cannot apply this '
    + '(no WordPress credentials); a Claude session applies it with the '
    + 'WordPress MCP. See the "Update WordPress page 1763" step in the '
    + 'exercise-creating skills for the safe procedure.',
  pageId: 1763,
  pageUrl: 'https://englishonline.training/activities/',
  buttons: BUTTONS.map(([section, hub, label, count]) => ({
    section: section,
    href: BASE + hub,
    label: label + ' (' + count + (count === 1 ? ' exercise)' : ' exercises)')
  }))
};

const dest = path.join(ROOT, 'data', 'wordpress-1763.json');
const next = JSON.stringify(out, null, 2) + '\n';
const changed = !fs.existsSync(dest) || fs.readFileSync(dest, 'utf8') !== next;
fs.writeFileSync(dest, next);

console.log('build-wordpress-hub: ' + out.buttons.length + ' button labels'
  + (changed ? ' — CHANGED, page 1763 needs updating' : ' — unchanged'));
if (changed) out.buttons.forEach(b => console.log('    ' + b.label));
