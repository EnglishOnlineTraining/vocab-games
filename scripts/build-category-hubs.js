#!/usr/bin/env node
'use strict';

/*
 * build-category-hubs.js — generates the exercise card list on every
 * per-category hub (`*-activities.html`).
 *
 * Why this exists: the per-year and per-course hubs were hand-maintained while
 * everything around them was generated. A new exercise landed in
 * data/exercises.json, the filterable index, the sitemap and the hub's own
 * JSON-LD — but its visible card had to be typed in by hand. On
 * 9g-activities.html that step was missed, so the page advertised the exercise
 * to crawlers in its ItemList while a student browsing the hub could not see or
 * reach it. Nothing generated the card list and nothing checked it.
 *
 * What it owns: the region between HUBCARDS:START and HUBCARDS:END on each hub.
 * Never hand-edit inside those markers — edit data/hub-cards.json and rerun.
 *
 * data/hub-cards.json holds the editorial text (icon, title, one-line meta,
 * tag) for every card, seeded from the hand-written HTML so nothing anyone
 * wrote was lost. An exercise in data/exercises.json with no entry there gets a
 * card derived from its own page and the entry is written back, so a new
 * exercise appears on its hub with no extra step and its wording stays editable
 * afterwards.
 *
 * A card whose href is not in data/exercises.json is a deliberate pin (an
 * unlisted class test, say) and is kept in place.
 */

const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');

const exercises = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', 'exercises.json'), 'utf8'));
const HC_PATH = path.join(ROOT, 'data', 'hub-cards.json');
const hubCards = JSON.parse(fs.readFileSync(HC_PATH, 'utf8'));

const START = '<!-- HUBCARDS:START — generated by scripts/build-category-hubs.js, do not edit by hand -->';
const END   = '<!-- HUBCARDS:END -->';

// Which exercises belong on which hub. Keyed the same way build-exercise-data.js
// buckets them, so the two cannot disagree about what a category contains.
const HUB_CATEGORY = {
  '7c-activities.html':  e => e.year === 7  && e.schoolType === 'oberschule',
  '7g-activities.html':  e => e.year === 7  && e.schoolType === 'gymnasium',
  '8c-activities.html':  e => e.year === 8  && e.schoolType === 'oberschule',
  '8g-activities.html':  e => e.year === 8  && e.schoolType === 'gymnasium',
  '9c-activities.html':  e => e.year === 9  && e.schoolType === 'oberschule',
  '9g-activities.html':  e => e.year === 9  && e.schoolType === 'gymnasium',
  '10c-activities.html': e => e.year === 10 && e.schoolType === 'oberschule',
  '10g-activities.html': e => e.year === 10 && e.schoolType === 'gymnasium',
  'abitur-activities.html':      e => e.year === 'abitur',
  'msa-activities.html':         e => e.year === 'msa',
  'uni-activities.html':         e => e.year === 'uni',
  'it-activities.html':          e => e.year === 'it',
  'business-activities.html':    e => e.year === 'business',
  'grammar-activities.html':     e => e.year === 'grammar',
  'esl-grammar-activities.html': e => e.year === 'esl'
};

// An Abitur pack's writing task, from its filename, decides which group it joins.
const ABITUR_GROUP = { 'text-analysis': 0, 'argumentative-writing': 1, 'writing-summaries': 2, 'mediation': 3 };
function abiturGroupFor(file) {
  const m = file.match(/^abitur-([a-z-]+?)-[a-z0-9-]+\.html$/);
  const key = m && Object.keys(ABITUR_GROUP).find(k => m[1] === k);
  return key ? ABITUR_GROUP[key] : null;
}

const TAG_STYLE = 'display:inline-block;margin-top:.4rem;font-size:.7rem;font-weight:700;'
  + 'letter-spacing:.05em;text-transform:uppercase;padding:.25rem .75rem;border-radius:20px;'
  + 'background:var(--blue-lt,#e8f2fb);color:var(--blue-mid,#1a6eb5)';

const SKILL_TAG = {
  grammar: 'Grammar', reading: 'Reading', writing: 'Writing',
  vocabulary: 'Vocabulary', listening: 'Listening'
};

function esc(s) {
  return String(s == null ? '' : s)
    .replace(/&(?!(?:amp|lt|gt|quot|#\d+|[a-z]+);)/gi, '&amp;');
}

/* ---- Deriving a card for an exercise nobody has written one for yet ---- */

function derive(e) {
  let icon = '📝', meta = '';
  try {
    const s = fs.readFileSync(path.join(ROOT, e.file), 'utf8');
    const fl = s.match(/<div class="welcome-flag">([\s\S]*?)<\/div>/);
    if (fl) icon = fl[1].trim();
    const d = s.match(/<meta name="description" content="([^"]*)"/);
    if (d) meta = d[1];
  } catch (_) { /* a registry entry with no page is build-exercise-data's problem */ }

  // The meta description is written for search results and opens with boilerplate
  // ("Free Year 9 English practice: ..."). The card wants the part after that.
  meta = meta.replace(/^[^:]{0,60}:\s*/, '').replace(/\s*$/, '');
  if (meta.length > 110) meta = meta.slice(0, 107).replace(/[\s,;]+\S*$/, '') + '…';
  if (!meta) meta = (e.blurb || '').split(' · ').slice(0, 3).join(' · ');

  const tag = (e.skills || []).map(s => SKILL_TAG[s]).filter(Boolean).slice(0, 2).join(' & ')
    || 'Exercise';
  return { href: e.file, icon: icon, title: e.title || e.file, meta: meta, tag: tag };
}

/* ---- Rendering ---- */

function renderCard(c, style) {
  if (style === 'gr-topic-card') {
    const links = ['      <a class="btn btn-gold btn-sm" href="' + c.href + '">'
      + (c.startLabel || 'Start exercise →') + '</a>']
      .concat((c.extraLinks || []).map(l =>
        '      <a class="' + l.cls + '" href="' + l.href + '">' + l.label + '</a>'));
    return '  <div class="gr-topic-card">\n'
      + '    <h2>' + c.icon + ' ' + esc(c.title) + '</h2>\n'
      + '    <p>' + esc(c.meta) + '</p>\n'
      + '    <div class="gr-topic-links">\n' + links.join('\n') + '\n'
      + '    </div>\n'
      + '  </div>';
  }
  // The card markup had drifted between <span> and <div> for icon/title/meta,
  // mixed inside the same hubs. .activity-card is display:flex, so both render
  // identically; <span> is the majority form and is now the only one emitted.
  const f = style === 'exercise-card'
    ? [['font-size:1.8rem', 'icon'],
       ['font-size:1.05rem;font-weight:700;color:var(--blue)', 'title'],
       ['font-size:.85rem;color:var(--muted)', 'meta'],
       [TAG_STYLE, 'tag']].map(([st, k]) => '      <span style="' + st + '">' + esc(c[k]) + '</span>')
    : ['icon', 'title', 'meta', 'tag'].map(k =>
        '      <span class="card-' + k + '">' + esc(c[k]) + '</span>');
  return '    <li><a class="' + style + '" href="' + c.href + '">\n' + f.join('\n') + '\n    </a></li>';
}

function renderHub(hub) {
  const { style, blocks } = hubCards[hub];
  if (style === 'gr-topic-card') {
    return blocks[0].cards.map(c => renderCard(c, style)).join('\n\n');
  }
  return blocks.map(b => {
    const h = b.heading
      ? '  <h3 class="group-heading"' + (b.heading.id ? ' id="' + b.heading.id + '"' : '')
        + '>' + b.heading.text + '</h3>\n\n'
      : '';
    return h + '  <ul class="cards-grid">\n'
      + b.cards.map(c => renderCard(c, style)).join('\n\n') + '\n  </ul>';
  }).join('\n\n');
}

/* ---- Reconcile the card list against the exercise registry ---- */

let added = 0;
const report = [];

for (const hub of Object.keys(HUB_CATEGORY)) {
  if (!hubCards[hub]) { console.error('✗ no card data for ' + hub); process.exitCode = 1; continue; }
  const entry = hubCards[hub];
  const mine = exercises.filter(HUB_CATEGORY[hub]);
  const have = new Set();
  entry.blocks.forEach(b => b.cards.forEach(c => have.add(c.href)));

  const missing = mine.filter(e => !have.has(e.file));
  for (const e of missing) {
    const card = derive(e);
    let bi = entry.blocks.length - 1;
    if (hub === 'abitur-activities.html') {
      const g = abiturGroupFor(e.file);
      if (g != null && entry.blocks[g]) bi = g;
    }
    entry.blocks[bi].cards.push(card);
    added++;
    report.push('  + ' + hub.replace('-activities.html', '').padEnd(12) + ' ' + e.file);
  }

  const pinned = [...have].filter(h => !mine.some(e => e.file === h));
  entry.pinned = pinned.length ? pinned : undefined;
  if (entry.pinned === undefined) delete entry.pinned;
}

/* ---- Write ---- */

let written = 0;
for (const hub of Object.keys(HUB_CATEGORY)) {
  if (!hubCards[hub]) continue;
  const file = path.join(ROOT, hub);
  const src = fs.readFileSync(file, 'utf8');
  const i = src.indexOf(START), j = src.indexOf(END);
  if (i === -1 || j === -1) {
    console.error('✗ ' + hub + ' has no HUBCARDS:START/END markers — run the migration first');
    process.exitCode = 1;
    continue;
  }
  const next = src.slice(0, i) + START + '\n' + renderHub(hub) + '\n' + src.slice(j);
  if (next !== src) { fs.writeFileSync(file, next); written++; }
}

fs.writeFileSync(HC_PATH, JSON.stringify(hubCards, null, 2) + '\n');

const total = Object.values(hubCards).reduce((n, h) => n + h.blocks.reduce((k, b) => k + b.cards.length, 0), 0);
console.log('build-category-hubs: ' + total + ' cards across ' + Object.keys(HUB_CATEGORY).length
  + ' hubs, ' + written + ' file(s) updated, ' + added + ' card(s) added from the registry.');
report.forEach(r => console.log(r));
